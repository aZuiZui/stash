#!/usr/bin/env python3
"""Write teldrive.properties (git-ignored) from your teldrive server's config.

The phone runs its own teldrive server against the same Postgres DB as your main teldrive
server, so it needs the same Telegram app id/hash, JWT secret and uploads encryption key.
These are baked into your APK at build time; the user only types the DB host/user/password.

Usage: gen-teldrive-secrets.py [CONFIG_DIR] [OUTPUT]
  CONFIG_DIR holds config.toml (teldrive), optionally rclone.conf (a [teldrive] remote) and
  channel-folders.txt; defaults to ./teldrive-config
  OUTPUT defaults to ./teldrive.properties
"""
import configparser
import pathlib
import sys
import tomllib
from urllib.parse import urlparse

root = pathlib.Path(__file__).resolve().parent.parent
cfg_dir = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else root / "teldrive-config"
out = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else root / "teldrive.properties"

conf = tomllib.loads((cfg_dir / "config.toml").read_text())
tg = conf.get("tg", {})
db = urlparse(conf["db"]["data-source"])

rc = configparser.ConfigParser(interpolation=None)
rc.read(cfg_dir / "rclone.conf")
remote = rc["teldrive"] if rc.has_section("teldrive") else {}

values = {
    "td.appId": tg["app-id"],
    "td.appHash": tg["app-hash"],
    "td.appVersion": tg.get("app-version", ""),
    "td.deviceModel": tg.get("device-model", ""),
    "td.systemVersion": tg.get("system-version", ""),
    "td.langPack": tg.get("lang-pack", ""),
    "td.jwtSecret": conf["jwt"]["secret"],
    "td.allowedUsers": ",".join(conf["jwt"].get("allowed-users", [])),
    "td.uploadsEncryptionKey": conf.get("tg", {}).get("uploads", {}).get("encryption-key", ""),
    # DB defaults only - never the DB user/password; the user types those in the app.
    "td.dbHost": db.hostname or "",
    "td.dbPort": db.port or 5432,
    "td.dbName": db.path.lstrip("/") or "postgres",
    "td.dbParams": db.query,
    # rclone remote settings, as in rclone.conf [teldrive]
    "td.rcloneEncryptFiles": remote.get("encrypt_files", "false"),
    "td.rcloneChunkSize": remote.get("chunk_size", "500M"),
    "td.rcloneUploadConcurrency": remote.get("upload_concurrency", "4"),
    "td.rcloneRandomChunkName": remote.get("random_chunk_name", "true"),
}


# Folder -> channel mappings for uploads (optional): channel-folders.txt next to config.toml, one
# "Folder/Sub|channel_id" per line (# comments allowed). Uploads into a mapped folder go to that
# Telegram channel. Written as "folder|channelId" pairs joined by ";".
mappings = []
folders_file = cfg_dir / "channel-folders.txt"
if folders_file.exists():
    for line in folders_file.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        folder, sep, channel = line.rpartition("|")
        if not sep or not folder.strip("/ ") or not channel.strip().lstrip("-").isdigit():
            print(f"note: skipped line in {folders_file.name}: {line!r}", file=sys.stderr)
            continue
        mappings.append(f"{folder.strip().strip('/')}|{channel.strip()}")
values["td.channelFolders"] = ";".join(mappings)


def esc(v):
    return str(v).replace("\\", "\\\\").replace("\n", "\\n").replace("=", "\\=").replace(":", "\\:")


out.write_text(
    "# Generated by scripts/gen-teldrive-secrets.py - SECRET, never commit.\n"
    + "".join(f"{k}={esc(v)}\n" for k, v in values.items())
)
out.chmod(0o600)
print(f"wrote {out} ({len(values)} keys) from {cfg_dir}")
